    #[test]
    fn missing_binary_means_placeholder_and_no_spawn() {
        // Point PATH at an empty dir: cava cannot be found, so the
        // state must be the honest placeholder and nothing spawns.
        let _env_guard = crate::diag::env_lock();
        let empty = std::env::temp_dir().join(format!("lyre-nopath-{}", std::process::id()));
        std::fs::create_dir_all(&empty).unwrap();
        let prev = std::env::var("PATH").ok();
        std::env::set_var("PATH", &empty);
        let mut viz = Viz::new();
        viz.maintain(true, 31);
        assert_eq!(viz.state, VizState::MissingBinary);
        assert!(viz.child.is_none(), "no process may spawn without the binary");
        // Even with respawn allowance, a missing binary never spawns.
        viz.allow_one_respawn();
        viz.maintain(true, 31);
        assert_eq!(viz.state, VizState::MissingBinary);
        match prev {
            Some(p) => std::env::set_var("PATH", p),
            None => std::env::remove_var("PATH"),
        }
        let _ = std::fs::remove_dir_all(&empty);
    }
