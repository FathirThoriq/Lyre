    #[test]
    fn display_lerp_attack_fast_release_capped() {
        let mut d = VizDisplay::default();
        // First frame primes outright (no fade-in from black).
        d.tick(&[255]);
        assert_eq!(d.values[0], 255.0, "primed to the first frame");
        // Silence: the fall is CAPPED at RELEASE per tick, not 1:1.
        d.tick(&[0]);
        assert_eq!(d.values[0], 255.0 - RELEASE, "one capped step down");
        d.tick(&[0]);
        assert_eq!(d.values[0], 255.0 - 2.0 * RELEASE);
        // Attack: from a low value toward a loud target, one tick
        // covers ATTACK of the distance (fast, but smoothed).
        let mut d2 = VizDisplay::from_values(&[0.0]);
        d2.tick(&[200]);
        let rose = d2.values[0];
        assert!(rose > 100.0 && rose < 200.0, "attack lands between: {}", rose);
        assert!((rose - 200.0 * ATTACK).abs() < 0.01, "attack = 65% of the gap: {}", rose);
    }

    #[test]
    fn peak_caps_hold_then_fall_slowly() {
        let mut d = VizDisplay::default();
        d.tick(&[255]);
        assert_eq!(d.peaks[0], 255.0);
        // Input drops to silence: the value falls at RELEASE/tick
        // while the peak HOLDS for PEAK_HOLD_TICKS ticks...
        for _ in 0..PEAK_HOLD_TICKS {
            d.tick(&[0]);
        }
        assert_eq!(d.peaks[0], 255.0, "peak still held after {} ticks", PEAK_HOLD_TICKS);
        assert!(d.values[0] < 255.0, "the bar itself fell meanwhile");
        // ...then the cap sinks at PEAK_FALL per tick (slow).
        d.tick(&[0]);
        assert_eq!(d.peaks[0], 255.0 - PEAK_FALL, "cap falls slowly");
        d.tick(&[0]);
        assert_eq!(d.peaks[0], 255.0 - 2.0 * PEAK_FALL);
        // But never below the live value.
        for _ in 0..200 {
            d.tick(&[0]);
        }
        assert_eq!(d.peaks[0], d.values[0]);
        assert_eq!(d.values[0], 0.0);
    }

