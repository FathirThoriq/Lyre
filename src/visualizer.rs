    #[test]
    fn template_line_is_braille_and_rises_with_the_spectrum() {
        // Rising ramp: the line must climb left -> right.
        let ramp: Vec<f32> = (0..SOURCE_BARS).map(|i| i as f32 * 16.0).collect();
        let d = VizDisplay::from_values(&ramp);
        let rows = render_style(VizStyle::Line, &d, 3, 12);
        assert_eq!(rows.len(), 3);
        let all: String = rows.concat();
        assert!(
            all.chars().any(|c| ('\u{2801}'..='\u{28ff}').contains(&c)),
            "braille dots present: {:?}",
            rows
        );
        // Left end is low (dots only in the bottom row), right end
        // is high (dots reach the top row).
        let left_bottom_only = !rows[0].chars().take(3).any(|c| c != ' ' && c != '\u{2800}');
        assert!(left_bottom_only, "left starts low: {:?}", rows);
        assert!(
            rows[0].chars().rev().take(3).any(|c| ('\u{2801}'..='\u{28ff}').contains(&c)),
            "right reaches the top row: {:?}",
            rows
        );
        // Flat zero -> the honest baseline: dots only in the
        // bottom row (the line sits at zero), nothing above it.
        let flat = VizDisplay::from_values(&[0.0; SOURCE_BARS]);
        let rows0 = render_style(VizStyle::Line, &flat, 3, 12);
        assert!(
            !rows0[0].chars().any(|c| ('\u{2801}'..='\u{28ff}').contains(&c))
                && !rows0[1].chars().any(|c| ('\u{2801}'..='\u{28ff}').contains(&c)),
            "silence has no dots above the baseline: {:?}",
            rows0
        );
    }

